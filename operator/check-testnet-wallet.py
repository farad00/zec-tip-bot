def capability_report(document):
    methods = document.get('methods') if isinstance(document, dict) else None
    if not isinstance(methods, list):
        raise ValueError('Unexpected wallet discovery document.')
    report = []
    for name in METHODS:
        method = next((m for m in methods if isinstance(m, dict) and m.get('name') == name), None)
        params = method.get('params', []) if method else []
        if not isinstance(params, list):
            raise ValueError('Unexpected wallet method parameter schema.')
        report.append({'method': name, 'available': method is not None, 'arguments': [
            p['name'] for p in params if isinstance(p, dict) and isinstance(p.get('name'), str)
            and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]{0,63}', p['name'])
        ]})
    return report


def binary_from_verified_archive():
    matches = []
    for archive in Path('/tmp').glob('zec-zallet.*/zallet.tar.gz'):
        with archive.open('rb') as stream:
            digest = hashlib.file_digest(stream, 'sha256').hexdigest()
        if digest == ARCHIVE_SHA:
            matches.append(archive)
    if not matches:
        raise ValueError('The verified Zallet download is missing from /tmp. No wallet was started.')
    TOOLS.mkdir(parents=True, exist_ok=True)
    destination = TOOLS / 'zallet-zaino'
    with tarfile.open(matches[0], 'r:gz') as tar:
        members = [m for m in tar.getmembers() if PurePosixPath(m.name).name == 'zallet-zaino']
        if len(members) != 1 or not members[0].isfile() or not 1_000_000 <= members[0].size <= 600_000_000:
            raise ValueError('Expected one regular Zaino executable in the verified release.')
        source = tar.extractfile(members[0])
        if source is None:
            raise ValueError('Could not read backend executable.')
        with source:
            data = source.read()
        if destination.exists():
            if destination.read_bytes() != data:
                raise ValueError('Existing backend differs; refusing to overwrite it.')
        else:
            with destination.open('xb') as out:
                out.write(data)
            destination.chmod(0o755)
    return destination


def log_hints(text):
    # Emit only fixed categories, never arbitrary subprocess logs or credentials.
    patterns = {
        'consensus_or_upgrade': r'consensus|network upgrade|\bNU7\b|branch.?id',
        'node_connection': r'connection refused|connect error|connection error|unauthori[sz]ed',
        'configuration': r'configuration error|unknown field|invalid value|TOML',
        'keystore_initialization': r'encryption.identity|keystore|key store|init-wallet-encryption',
        'wallet_tasks_started': r'Spawned Zallet tasks',
    }
    return [name for name, pattern in patterns.items() if re.search(pattern, text, re.I)]


def initialization_commands(binary, directory):
    if (directory.is_symlink() or directory.resolve().parent != PROBES.resolve()
            or not directory.name.startswith('check-')):
        raise ValueError('Encryption setup is restricted to a new temporary check directory.')
    identity = directory / 'encryption-identity.txt'
    if identity.exists() or identity.is_symlink():
        raise ValueError('Refusing to replace an existing encryption identity.')
    prefix = [str(binary), '--datadir', str(directory)]
    return [prefix + ['generate-encryption-identity', '--output', str(identity)],
            prefix + ['init-wallet-encryption']]


def initialize_empty_wallet(binary, directory, account, log):
    for command in initialization_commands(binary, directory):
        completed = subprocess.run(command, stdin=subprocess.DEVNULL, stdout=log,
            stderr=subprocess.STDOUT, timeout=20, cwd=directory,
            user=account.pw_uid, group=account.pw_gid, extra_groups=[], umask=0o077,
            env={'PATH': '/usr/bin:/bin', 'HOME': str(directory), 'LANG': 'C.UTF-8'})
        if completed.returncode:
            raise ValueError('Empty-wallet encryption setup failed; run this helper with --diagnose.')
        # Generation writes to a file, never stdout. Inspect only ownership/mode, not key contents.
        identity = directory / 'encryption-identity.txt'
        metadata = identity.lstat()
        if not stat.S_ISREG(metadata.st_mode) or stat.S_IMODE(metadata.st_mode) != 0o600 or metadata.st_uid != account.pw_uid:
            raise ValueError('The temporary encryption identity must be an owner-only regular file.')


def safe_excerpt(text, credentials=()):
    text = re.sub(r'\x1b\[[0-9;]*[A-Za-z]', '', text)
    for credential in credentials:
        if credential:
            text = text.replace(credential, '[credential removed]')
            password = credential.partition(':')[2]
            if len(password) >= 8:
                text = text.replace(password, '[credential removed]')
    text = re.sub(r'(?i)(authorization\s*[:=]\s*)(?:Basic|Bearer)\s+[^\s"\']+', r'\1[removed]', text)
    text = re.sub(r'(?i)(\b(?:password|passphrase|rpcpassword|access_token|oauth_token|client_secret)\s*[=:]\s*)(?:"[^"\n]*"|\'[^\'\n]*\'|\S+)', r'\1[removed]', text)
    text = re.sub(r'(?<![A-Za-z0-9])[A-Za-z0-9_+/=-]{40,}(?![A-Za-z0-9])', '[long value removed]', text)
    lines = []
    for line in text.splitlines():
        if re.search(r'(?i)(mnemonic|seed\s*phrase|recovery\s*phrase|AGE-SECRET-KEY)', line):
            line = '[recovery-material line removed]'
        if line.strip():
            lines.append(line[:500])
    return lines[-35:]


def last_check_log():
    root = PROBES.resolve()
    if PROBES.is_symlink():
        raise ValueError('Unexpected diagnostic directory.')
    logs = []
    for directory in PROBES.glob('check-*'):
        log = directory / 'check.log'
        if directory.is_symlink() or log.is_symlink() or not log.is_file():
            continue
        if directory.resolve().parent != root or log.resolve().parent != directory.resolve():
            raise ValueError('Diagnostic log is outside the temporary-check directory.')
        logs.append(log)
    if not logs:
        raise ValueError('No previous temporary wallet check log was found.')
    return max(logs, key=lambda p: p.stat().st_mtime_ns)


def read_log_tail(log):
    with log.open('rb') as stream:
        stream.seek(max(0, log.stat().st_size - 32_768))
        return stream.read(32_768).decode(errors='replace')


def diagnose():
    log = last_check_log()
    credentials = []
    for directory in (NODE_RPC, log.parent):
        try:
            credentials.append(cookie_file(directory).read_text().strip())
        except (ValueError, OSError):
            pass
    text = read_log_tail(log)
    print(json.dumps({'readOnly': True, 'previousCheckLog': True,
                      'diagnostics': safe_excerpt(text, credentials)}, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--diagnose', action='store_true', help='Read and redact the previous check log only.')
    args = parser.parse_args()
    if sys.platform != 'linux' or os.geteuid() != 0:
        raise ValueError('Run this helper in the VPS root SSH terminal.')
    if Path('/etc/hostname').read_text().strip() != 'vmi3703861':
        raise ValueError('Unexpected VPS hostname.')
    if args.diagnose:
        diagnose()
        return
    import pwd
    cookie = cookie_file(NODE_RPC)
    info = rpc(18232, cookie, 'getblockchaininfo')
    if not isinstance(info, dict) or info.get('chain') not in ('test', 'testnet'):
        raise ValueError('The connected node is not verified Testnet.')
    # Never contact an existing wallet instance with a fresh helper's credentials.
    import socket
    with socket.socket() as check_socket:
        if check_socket.connect_ex(('127.0.0.1', 28234)) == 0:
            raise ValueError('The temporary check port is already occupied.')
    binary = binary_from_verified_archive()
    account = pwd.getpwnam('zectip-chain')
    PROBES.mkdir(mode=0o700, exist_ok=True)
    directory = Path(tempfile.mkdtemp(prefix='check-', dir=PROBES))
    directory.chmod(0o700)
    cfg = directory / 'zallet.toml'
    cfg.write_text(config(cookie))
    cfg.chmod(0o600)
    os.chown(cfg, account.pw_uid, account.pw_gid)
    os.chown(directory, account.pw_uid, account.pw_gid)
    # Parent is root-owned; allow only this service user to traverse it.
    os.chown(PROBES, account.pw_uid, account.pw_gid)
    log_path = directory / 'check.log'
    report = {'nodeNetwork': info['chain'], 'nodeHeightAtCheck': info.get('blocks'),
              'connectivityCheckOnly': True, 'currentTestnetTipVerified': False,
              'spendingEnabled': False, 'spendingKeysCreated': False}
    proc = None
    try:
        with log_path.open('xb') as log:
            log_path.chmod(0o600)
            initialize_empty_wallet(binary, directory, account, log)
            report['emptyWalletEncryptionInitialized'] = True
            proc = subprocess.Popen([str(binary), '--datadir', str(directory), 'start'],
                stdin=subprocess.DEVNULL, stdout=log, stderr=subprocess.STDOUT,
                user=account.pw_uid, group=account.pw_gid, extra_groups=[], umask=0o077,
                start_new_session=True, cwd=directory,
                env={'PATH': '/usr/bin:/bin', 'HOME': str(directory), 'LANG': 'C.UTF-8'})
            deadline = time.monotonic() + 45
            while proc.poll() is None and time.monotonic() < deadline:
                time.sleep(1)
                try:
                    wallet_cookie = cookie_file(directory)
                    discovery = rpc(28234, wallet_cookie, 'rpc.discover')
                    report['walletRpcConnected'] = True
                    report['capabilities'] = capability_report(discovery)
                    try:
                        status = rpc(28234, wallet_cookie, 'getwalletstatus')
                        report['walletStatusFieldNames'] = sorted(k for k in status
                            if isinstance(k, str) and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]{0,63}', k)) if isinstance(status, dict) else []
                    except (ValueError, urllib.error.URLError, OSError):
                        report['walletStatusRead'] = 'not ready'
                    break
                except (ValueError, urllib.error.URLError, OSError):
                    pass
            if 'walletRpcConnected' not in report:
                report['walletRpcConnected'] = False
                report['processExitCode'] = proc.poll()
    finally:
        if proc is not None and proc.poll() is None:
            try:
                os.killpg(proc.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                os.killpg(proc.pid, signal.SIGKILL)
                proc.wait()
    report['diagnosticCategories'] = log_hints(read_log_tail(log_path))
    if not report.get('walletRpcConnected'):
        credentials = [cookie.read_text().strip()]
        try:
            credentials.append(cookie_file(directory).read_text().strip())
        except (ValueError, OSError):
            pass
        report['diagnosticLines'] = safe_excerpt(read_log_tail(log_path), credentials)
    report['temporaryWalletStopped'] = True
    print(json.dumps(report, indent=2))
    print('Only an empty temporary wallet was checked. The node keeps syncing.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        print('Check stopped: ' + (str(exc) if isinstance(exc, ValueError) else type(exc).__name__), file=sys.stderr)
        sys.exit(1)
