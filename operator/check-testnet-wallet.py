ARCHIVE_SHA = '1df2398df016ae6e9a1cba3f8ef0cc86ca0d7b48a0934b34df6f68114ebe9306'
NODE_RPC = Path('/var/lib/zec-tip-bot-chain-testnet/rpc')
TOOLS = Path('/opt/zec-tip-bot-chain/zallet-v0.1.0-beta.3')
PROBES = Path('/var/lib/zec-tip-bot-wallet-checks')
METHODS = ('z_getnewaccount', 'z_getaddressforaccount', 'z_getbalanceforaccount',
           'z_listaccounts', 'pczt_create', 'pczt_inspect', 'pczt_prove', 'pczt_sign',
           'pczt_extract', 'getwalletstatus')


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


def cookie_file(directory):
    # Search only the dedicated authentication directory, at most one network subdir.
    candidates = []
    for pattern in ('*', '*/*'):
        for path in directory.glob(pattern):
            if path.is_file() and not path.is_symlink() and 'cookie' in path.name.lower():
                if directory.resolve() not in path.resolve().parents:
                    raise ValueError('Unexpected cookie location.')
                candidates.append(path)
    if len(candidates) != 1:
        raise ValueError('Expected one local authentication cookie; node may still be starting.')
    return candidates[0]


def rpc(port, cookie, method):
    if method not in ('getblockchaininfo', 'rpc.discover', 'getwalletstatus'):
        raise ValueError('Only read operations are permitted in this check.')
    credential = cookie.read_text().strip()
    if not re.fullmatch(r'[A-Za-z0-9_]+:[!-~]{1,4096}', credential):
        raise ValueError('Unexpected authentication cookie format.')
    body = json.dumps({'jsonrpc': '2.0', 'id': 'wallet-check', 'method': method, 'params': []}).encode()
    req = urllib.request.Request(f'http://127.0.0.1:{port}', data=body, headers={
        'Content-Type': 'application/json',
        'Authorization': 'Basic ' + base64.b64encode(credential.encode()).decode(),
    })
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
    with opener.open(req, timeout=5) as response:
        raw = response.read(4_000_001)
    if len(raw) > 4_000_000:
        raise ValueError('Unexpectedly large read response.')
    payload = json.loads(raw)
    if payload.get('id') != 'wallet-check' or payload.get('error'):
        raise ValueError('The local read operation is not ready or was rejected.')
    return payload.get('result')


